def resolve_keycode(symbol: str) -> int:
    """Look up a ZMK keycode symbol. Raises KeyError if unknown."""
    return KEYCODES[symbol]


def apply_modifier(modifier_fn: str, keycode: int) -> int:
    """Apply a modifier function like LG/LS/LC/LA to a keycode."""
    mod_bit = MODIFIER_BITS[modifier_fn]
    return (mod_bit << 24) | keycode
